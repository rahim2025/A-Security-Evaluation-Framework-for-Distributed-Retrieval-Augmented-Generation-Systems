"""
attack/Mia_attack/tune_weights.py

Revision 7: a properly-gated weight re-tuning, responding directly to the
user-raised finding that the attack (composite score, tuned by human
judgment across Revisions 2-4) does not have confirmed generalization to
unseen data -- Revision 6's 10-seed held-out composite AUC (0.522) had a
95% CI that included chance.

This script does NOT repeat the mistake already diagnosed twice in this
project (tuning weights, then evaluating on the same seeds used to tune
them). It enforces a real split:

  DEV_SEEDS  (13 seeds, all previously observed in Revisions 5-6: 0, 1, 42,
             7, 13, 880, 496, 356, 820, 741, 926, 912, 662) -- used freely
             to search for weights. These seeds are not "blind" anymore --
             every one of their outcomes has already been looked at in this
             project's prior revisions -- so there is no pretense of
             held-out validity here. This is the training set, full stop.

  TEST_SEEDS (5 fresh seeds, generated by this script's own master seed,
             NEVER queried, computed, or looked at before this script runs)
             -- used exactly once, at the end, with the weights already
             locked in from the dev search. Whatever AUC comes out is
             reported as-is.

Two commands:
  python tune_weights.py collect --split dev     # fetch + save raw per-document signals for DEV_SEEDS
  python tune_weights.py search                  # grid-search weights on the saved DEV_SEEDS data, print + save the winner
  python tune_weights.py collect --split test     # fetch + save raw per-document signals for TEST_SEEDS
  python tune_weights.py evaluate                 # score TEST_SEEDS data with the locked-in weights -- run this exactly once
"""
from __future__ import annotations

import argparse
import itertools
import json
import os
import sys
import time
from typing import Any, Dict, List

import numpy as np
import requests
from sklearn.metrics import roc_auc_score

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from attack.Mia_attack.mia_attack import (  # noqa: E402
    CORPUS_JSONL,
    DEFAULT_MEMBERS,
    DEFAULT_NONMEMBERS,
    LLM_SERVICE_URL,
    _answer_length_ratio,
    _certainty_score,
    _cosine_similarity,
    _decision_match,
    _normalize_similarity,
    _parse_llm_response,
    load_membership_documents,
)

# Discovered live this session: some specific PubMedQA questions make
# drag_llm_service hang for 120s+ (confirmed reproducible via direct curl,
# not a fluke -- see reports/MIA_Security_Analysis_Report.md Revision 7).
# mia_attack.py's shared _query_llm() hardcodes a 120s timeout, which makes
# a full 13-seed x 50-doc collection impractically slow if even a handful of
# documents hit this. This local wrapper uses a much shorter timeout for
# tuning-data collection specifically -- a timeout is treated the same way
# an empty response already is elsewhere in this codebase (sim=0,
# decision_match=False, certainty=0, length_ratio=0), not as an error to
# retry or crash on. This does NOT change mia_attack.py's own _query_llm
# behavior or timeout for the production attack.
_QUERY_TIMEOUT_SECONDS = 20


def _query_llm_fast(question: str, url: str, api_key: str = "") -> str:
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["X-API-Key"] = api_key
    try:
        r = requests.post(
            f"{url}/query", json={"query": question}, headers=headers,
            timeout=_QUERY_TIMEOUT_SECONDS,
        )
        if r.status_code == 200:
            return _parse_llm_response(r.json())
    except Exception:
        pass
    return ""

try:
    from sentence_transformers import SentenceTransformer
except ImportError as exc:  # pragma: no cover
    raise ImportError("pip install sentence-transformers") from exc

EMBEDDING_MODEL = "all-MiniLM-L6-v2"

# DEV_SEEDS: every seed this project has ever observed. Not held-out --
# used freely for weight search.
DEV_SEEDS = [0, 1, 42, 7, 13, 880, 496, 356, 820, 741, 926, 912, 662]

# TEST_SEEDS: generated fresh, never queried before, held out from the
# search below. Reproducible: [s for s in random.Random(20260710).sample(
# range(1000), 30) if s not in <all 13 DEV_SEEDS>][:5]
TEST_SEEDS = [865, 659, 693, 783, 154]

_DATA_DIR = os.path.join(_ROOT, "attack_logs")
DEV_DATA_PATH = os.path.join(_DATA_DIR, "tune_weights_dev_signals.json")
TEST_DATA_PATH = os.path.join(_DATA_DIR, "tune_weights_test_signals.json")
WEIGHTS_PATH = os.path.join(_DATA_DIR, "tune_weights_locked.json")


def _collect_raw_signals(seeds: List[int], llm_url: str, api_key: str,
                          n_members: int, n_nonmembers: int) -> List[Dict[str, Any]]:
    """
    For each document in each seed, records the four RAW per-document
    signals (not a composite) plus the true label -- so arbitrary weight
    vectors can be scored against this data afterward without any further
    live LLM calls.

    Uses `_query_llm_fast` (20s timeout) instead of mia_attack.py's shared
    `_query_llm` (120s timeout) -- see module docstring for why: some
    specific questions were confirmed this session to hang the live service
    for 120s+, which would make a 13-seed x 50-doc collection impractically
    slow. A timeout here is treated as an empty response, same fallback
    behavior _query_llm already has -- not retried or treated as an error.
    """
    encoder = SentenceTransformer(EMBEDDING_MODEL)
    rows: List[Dict[str, Any]] = []
    n_timeouts = 0
    n_total_queries = 0
    for seed in seeds:
        members, non_members = load_membership_documents(
            n_members, n_nonmembers, seed, CORPUS_JSONL, probes_per_doc=4,
        )
        doc_counter = 0
        total_docs = len(members) + len(non_members)
        for label, documents in ((1, members), (0, non_members)):
            for qa_list in documents:
                doc_counter += 1
                if doc_counter % 5 == 0 or doc_counter == total_docs:
                    print(f"    [tune-weights] seed={seed} doc {doc_counter}/{total_docs} "
                          f"[timeouts: {n_timeouts}/{n_total_queries}]", flush=True)
                sims, lens_, certs, matches = [], [], [], []
                for qa in qa_list:
                    t0 = time.time()
                    response = _query_llm_fast(qa["question"], llm_url, api_key)
                    n_total_queries += 1
                    if not response.strip() and time.time() - t0 >= _QUERY_TIMEOUT_SECONDS - 1:
                        n_timeouts += 1
                    gold_decision = qa.get("decision", "")
                    if response.strip():
                        emb_r = encoder.encode([response], convert_to_numpy=True)[0]
                        emb_c = encoder.encode([qa["context"]], convert_to_numpy=True)[0]
                        sim = _cosine_similarity(emb_r, emb_c)
                    else:
                        sim = 0.0
                    sims.append(sim)
                    lens_.append(_answer_length_ratio(response, qa["answer"]))
                    certs.append(_certainty_score(response))
                    matches.append(1.0 if _decision_match(response, gold_decision) else 0.0)
                best = int(np.argmax(sims)) if sims else 0
                rows.append({
                    "seed": seed,
                    "label": label,
                    "norm_sim": _normalize_similarity(sims[best] if sims else 0.0),
                    "certainty": certs[best] if certs else 0.0,
                    "length_ratio": lens_[best] if lens_ else 0.0,
                    "decision_match": (sum(matches) / len(matches)) if matches else 0.0,
                })
        print(f"  [tune-weights] seed={seed} collected ({len(members)} members, {len(non_members)} non-members)"
              f"  [timeouts so far: {n_timeouts}/{n_total_queries}]", flush=True)
    print(f"  [tune-weights] TOTAL timeouts: {n_timeouts}/{n_total_queries} queries "
          f"({100.0 * n_timeouts / max(n_total_queries, 1):.1f}%) -- treated as empty responses, not retried")
    return rows


def cmd_collect(args: argparse.Namespace) -> None:
    seeds = DEV_SEEDS if args.split == "dev" else TEST_SEEDS
    out_path = DEV_DATA_PATH if args.split == "dev" else TEST_DATA_PATH
    print(f"[tune-weights] Collecting raw per-document signals for {args.split} seeds: {seeds}")
    rows = _collect_raw_signals(seeds, args.llm_url, args.api_key, args.n_members, args.n_nonmembers)
    os.makedirs(_DATA_DIR, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(rows, fh, indent=2)
    print(f"[tune-weights] Wrote {len(rows)} document rows -> {out_path}")


def _mean_per_seed_auc(rows: List[Dict[str, Any]], w: Dict[str, float]) -> float:
    seeds = sorted(set(r["seed"] for r in rows))
    aucs = []
    for seed in seeds:
        sub = [r for r in rows if r["seed"] == seed]
        y = np.array([r["label"] for r in sub])
        scores = np.array([
            w["decision"] * r["decision_match"] + w["sim"] * r["norm_sim"]
            + w["cert"] * r["certainty"] + w["len"] * r["length_ratio"]
            for r in sub
        ])
        if len(np.unique(y)) > 1 and len(np.unique(scores)) > 1:
            aucs.append(roc_auc_score(y, scores))
        else:
            aucs.append(0.5)
    return float(np.mean(aucs))


def cmd_search(args: argparse.Namespace) -> None:
    with open(DEV_DATA_PATH, encoding="utf-8") as fh:
        rows = json.load(fh)
    print(f"[tune-weights] Loaded {len(rows)} dev rows across {len(set(r['seed'] for r in rows))} seeds")

    step = args.step
    grid = [round(i * step, 10) for i in range(int(round(1.0 / step)) + 1)]
    best = None
    results = []
    for wd, ws, wc in itertools.product(grid, grid, grid):
        wl = round(1.0 - wd - ws - wc, 10)
        if wl < -1e-9 or wl > 1.0 + 1e-9:
            continue
        wl = max(wl, 0.0)
        w = {"decision": wd, "sim": ws, "cert": wc, "len": wl}
        score = _mean_per_seed_auc(rows, w)
        results.append((score, w))
        if best is None or score > best[0]:
            best = (score, w)

    results.sort(key=lambda x: -x[0])
    print("\n[tune-weights] Top 10 weight vectors by mean per-seed AUC on DEV_SEEDS:")
    for score, w in results[:10]:
        print(f"  mean_dev_auc={score:.4f}  decision={w['decision']:.2f} sim={w['sim']:.2f} "
              f"cert={w['cert']:.2f} len={w['len']:.2f}")

    best_score, best_w = best
    print(f"\n[tune-weights] WINNER: mean_dev_auc={best_score:.4f}  weights={best_w}")

    os.makedirs(_DATA_DIR, exist_ok=True)
    with open(WEIGHTS_PATH, "w", encoding="utf-8") as fh:
        json.dump({"weights": best_w, "mean_dev_auc": best_score, "grid_step": step,
                   "dev_seeds": DEV_SEEDS, "n_candidates": len(results)}, fh, indent=2)
    print(f"[tune-weights] Locked weights written -> {WEIGHTS_PATH}")
    print("[tune-weights] These weights are now FROZEN. Next step: collect --split test, then evaluate.")


def cmd_evaluate(args: argparse.Namespace) -> None:
    with open(WEIGHTS_PATH, encoding="utf-8") as fh:
        locked = json.load(fh)
    w = locked["weights"]
    print(f"[tune-weights] Evaluating LOCKED weights (chosen on DEV_SEEDS only): {w}")

    with open(TEST_DATA_PATH, encoding="utf-8") as fh:
        rows = json.load(fh)
    test_seeds_present = sorted(set(r["seed"] for r in rows))
    print(f"[tune-weights] Loaded {len(rows)} test rows across seeds: {test_seeds_present}")
    assert set(test_seeds_present) <= set(TEST_SEEDS), (
        "Test data contains a seed not in the reserved TEST_SEEDS list -- refusing to evaluate, "
        "this would not be a fair held-out test."
    )

    per_seed = {}
    for seed in test_seeds_present:
        sub = [r for r in rows if r["seed"] == seed]
        y = np.array([r["label"] for r in sub])
        scores = np.array([
            w["decision"] * r["decision_match"] + w["sim"] * r["norm_sim"]
            + w["cert"] * r["certainty"] + w["len"] * r["length_ratio"]
            for r in sub
        ])
        auc = roc_auc_score(y, scores) if len(np.unique(y)) > 1 and len(np.unique(scores)) > 1 else 0.5
        per_seed[seed] = round(float(auc), 4)

    aucs = list(per_seed.values())
    mean_auc = float(np.mean(aucs))
    std_auc = float(np.std(aucs, ddof=1)) if len(aucs) > 1 else 0.0
    n = len(aucs)
    se = std_auc / (n ** 0.5) if n > 1 else 0.0
    # t critical value for df=n-1, 95% two-sided (hardcoded small table for n up to ~10)
    t_table = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447,
               7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228}
    t_crit = t_table.get(n - 1, 1.96)
    ci = (round(mean_auc - t_crit * se, 4), round(mean_auc + t_crit * se, 4))

    print(f"\n[tune-weights] TRUE HELD-OUT RESULT (never seen during search) -- per seed: {per_seed}")
    print(f"[tune-weights] Mean AUC on fresh test seeds: {mean_auc:.4f}   95% CI: {ci}")
    print(f"[tune-weights] Compare to production weights' dev-set mean_dev_auc: {locked['mean_dev_auc']:.4f}")

    out_path = os.path.join(_DATA_DIR, "tune_weights_final_result.json")
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump({"weights": w, "per_seed_auc": per_seed, "mean_auc": round(mean_auc, 4),
                   "std_auc": round(std_auc, 4), "ci_95": ci, "n_test_seeds": n}, fh, indent=2)
    print(f"[tune-weights] Wrote {out_path}")


def main() -> None:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)

    c1 = sub.add_parser("collect")
    c1.add_argument("--split", choices=["dev", "test"], required=True)
    c1.add_argument("--llm_url", default=LLM_SERVICE_URL)
    c1.add_argument("--api_key", default="")
    c1.add_argument("--n_members", type=int, default=DEFAULT_MEMBERS)
    c1.add_argument("--n_nonmembers", type=int, default=DEFAULT_NONMEMBERS)
    c1.set_defaults(func=cmd_collect)

    c2 = sub.add_parser("search")
    c2.add_argument("--step", type=float, default=0.05)
    c2.set_defaults(func=cmd_search)

    c3 = sub.add_parser("evaluate")
    c3.set_defaults(func=cmd_evaluate)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
